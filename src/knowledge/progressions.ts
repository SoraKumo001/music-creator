const BY_ID = new Map(PROGRESSIONS.map((card) => [card.id, card]));

export function progressionById(id: string): ProgressionCard | undefined {
  return BY_ID.get(id);
}

export function cardsForGenre(genre: string): ProgressionCard[] {
  return PROGRESSIONS.filter((card) => card.genres.includes(genre));
}

/** カードを指定キーのコード記号へ実現する */
export function realizeCard(card: ProgressionCard, key: KeyContext | string): string[] {
  return realizeNumerals(card.numerals, typeof key === "string" ? parseKeyName(key) : key);
}
